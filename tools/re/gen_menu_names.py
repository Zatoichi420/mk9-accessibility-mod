"""Generates native/mk9hook/src/menu_names.inc from the decoded game text.

The main menu draws item names as pictures, so the hooks only see each
item's description. This table maps descriptions back to item names.

Usage: python gen_menu_names.py <decoded Coalesced_eng.txt> <output .inc>
(Decode Localization/Coalesced.eng with zlib, skipping its 4-byte size
prefix, then invert every byte.)
"""
import sys


def main(src, dst):
    text = open(src, 'rb').read().decode('latin-1')
    section = text[text.index('[MainMenu]'):]
    section = section[:section.index('\n[', 5)]
    values = {}
    for line in section.splitlines():
        if '=' in line:
            key, value = line.split('=', 1)
            values[key.strip()] = value.strip().strip('"')
    pairs, seen = [], set()
    for key, desc in values.items():
        if not key.endswith('Desc') or key[:-4] not in values:
            continue
        if not desc or 'Xbox' in key or 'PS3' in key or desc in seen:
            continue
        seen.add(desc)
        pairs.append((desc, values[key[:-4]]))

    def esc(s):
        return s.replace('\\', '\\\\').replace('"', '\\"')

    lines = [
        '// Generated by tools/re/gen_menu_names.py from Coalesced.eng [MainMenu].',
        '// The main menu shows item names as pictures; only descriptions reach',
        '// the hooks, so each description maps back to its item name.',
    ]
    lines += ['{"%s", "%s"},' % (esc(d), esc(n)) for d, n in pairs]
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(len(pairs), 'menu items')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
